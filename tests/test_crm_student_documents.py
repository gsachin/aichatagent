@pytest.mark.anyio
async def test_the_file_name_keeps_the_original_and_stays_unique(crm_on, client, store, pdf):
    """
    The admissions team reads these names, so the student's own file name is
    kept — prefixed with the row id so a re-upload of a *different* file is not
    mistaken for the same one.
    """
    sent, state = client
    state["responses"] = scripted(ok_listing(), init_ok(), chunk_ok(), complete_ok())

    await upload(path=pdf)

    init = sent[1]["body"].decode()
    assert "C852F7D9_RAG.md.pdf" in init


@pytest.mark.anyio
async def test_a_large_document_is_chunked(crm_on, client, store, tmp_path, override_settings):
    override_settings(CRM_UPLOAD_CHUNK_BYTES=1024)
    big = tmp_path / "big.pdf"
    big.write_bytes(b"%PDF" + b"y" * 5000)
    sent, state = client
    state["responses"] = scripted(ok_listing(), init_ok(), chunk_ok(), chunk_ok(),
                                  chunk_ok(), chunk_ok(), chunk_ok(), chunk_ok(), complete_ok())

    await upload(path=str(big))

    chunks = [s for s in sent if s["path"].endswith("/chunks")]
    assert len(chunks) == 5, "5004 bytes in 1KB chunks"
    # The first chunk starts with the file's own bytes (the header is 4 bytes,
    # so 1020 of the remaining 1024 are payload), and the last chunk is the tail.
    assert b"%PDF" in chunks[0]["body"]
    assert b"y" * 1000 in chunks[0]["body"]
    assert b"y" in chunks[-1]["body"]


