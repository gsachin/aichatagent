"""
Uploading the student's own documents — the transcript behind the offer.

The offer letter is generated by us; these files are the ones that justify it,
and until now they never left this machine: ``lead_documents`` had no CRM
columns and nothing uploaded them. The admissions team could see an offer
without ever seeing what supported it.

They share the chunked transfer with the offer letter (same three calls, same
never-retry-on-complete rule) and differ in two places that these tests pin:
the document type comes from a mapping onto the org's own vocabulary, and the
bookkeeping lives on the document row rather than the offer row.
"""

