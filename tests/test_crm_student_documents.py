@pytest.mark.anyio
async def test_a_duplicate_is_adopted_not_re_uploaded(crm_on, client, store, pdf):
    """
    Crash recovery: a previous attempt created the document but never recorded
    it. Matching on our deterministic file name finds it.
    """
    sent, state = client
    state["responses"] = scripted(httpx.Response(200, json=[
        {"document_id": "068EXISTING", "file_name": "C852F7D9_RAG.md.pdf",
         "document_type": "Academic Transcript"},
    ]))

    assert await upload(path=pdf) == "068EXISTING"
    assert len(sent) == 1, "only the listing call — no second copy created"
    assert store["recorded"][-1]["status"] == "uploaded"


@pytest.mark.anyio
async def test_an_ambiguous_complete_is_recorded_as_unknown(crm_on, client, store, pdf):
    """A 500 on complete may mean the document exists; it must never be retried."""
    sent, state = client
    state["responses"] = scripted(ok_listing(), init_ok(), chunk_ok(),
                                  httpx.Response(500, json={"detail": "boom"}))

    assert await upload(path=pdf) == ""
    completes = [s for s in sent if s["path"].endswith("/complete")]
    assert len(completes) == 1, "not retried — that could duplicate the document"
    assert store["recorded"][-1]["status"] == "unknown"


@pytest.mark.anyio
async def test_an_unavailable_listing_skips_rather_than_risking_a_duplicate(
    crm_on, client, store, pdf
):
    sent, state = client
    state["responses"] = scripted(httpx.Response(500, json={"detail": "listing down"}))

    assert await upload(path=pdf) == ""
    assert not any(s["path"].endswith("/uploads") for s in sent)


# ── the mapping itself ───────────────────────────────────────────────────────

def test_document_types_map_onto_the_org_vocabulary():
    assert ident.map_document_type("transcript") == "Academic Transcript"
    assert ident.map_document_type("id_proof") == "ID Document"
    assert ident.map_document_type("other") == "Other"


def test_an_unrecognised_document_type_falls_back_rather_than_failing():
    """The document is real; filing it under a general label beats losing it."""
    assert ident.map_document_type("something-new") == "Other"
    assert ident.map_document_type("") == "Other"
    assert ident.map_document_type(None) == "Other"


def test_every_mapped_value_is_a_value_the_org_accepts():
    """
    The picklist is restricted — the API validates nothing, so a typo here
    becomes a 500 at upload time. These are the values read from the org.
    """
    accepted = {
        "Academic Transcript", "Resume", "Financial Document", "ID Document",
        "Admission Call Recording", "Chatbot Conversation Record", "Test Score",
        "Recommendation Letter", "Other", "10th Marksheet", "12th Marksheet",
        "Diploma Marksheet", "Bachelor's Last-Semester Result", "IELTS Score",
        "Diploma Last-Semester Result",
    }
    for value in ident.DOCUMENT_TYPE_MAP.values():
        assert value in accepted, f"{value!r} is not in the org's Document_Type__c"
