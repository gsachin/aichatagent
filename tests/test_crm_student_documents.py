def scripted(*responses):
    return list(responses)


def upload(doc_id=DOC_ID, path="/tmp/x.pdf", doc_type="transcript", name="RAG.md.pdf"):
    return docs_mod.upload_student_document(
        lead_id="lead-1", doc_id=doc_id, file_path=path, doc_type=doc_type,
        original_name=name,
    )


@pytest.fixture
def pdf(tmp_path):
    p = tmp_path / "RAG.md.pdf"
    p.write_bytes(PDF)
    return str(p)


def ok_listing() -> httpx.Response:
    return httpx.Response(200, json=[])


def init_ok() -> httpx.Response:
    return httpx.Response(200, json={"upload_id": UPLOAD_ID, "total_chunks": 1,
                                     "status": "initiated"})


def chunk_ok() -> httpx.Response:
    return httpx.Response(200, json={"upload_id": UPLOAD_ID, "chunk_number": 1,
                                     "received_chunks": 1, "total_chunks": 1})


def complete_ok(document_id="068T100000cVgi7IAC") -> httpx.Response:
    return httpx.Response(200, json={"upload_id": UPLOAD_ID, "status": "completed",
                                     "document": {"document_id": document_id,
                                                  "file_name": "x.pdf"}})


# ── the happy path ───────────────────────────────────────────────────────────

@pytest.mark.anyio
async def test_a_transcript_reaches_the_crm(crm_on, client, store, pdf):
    sent, state = client
    state["responses"] = scripted(ok_listing(), init_ok(), chunk_ok(), complete_ok())

    assert await upload(path=pdf) == "068T100000cVgi7IAC"

    paths = [s["path"] for s in sent]
    assert paths[0] == "/admissions/APP-28B9A16C28/documents"
    assert paths[1] == "/admissions/APP-28B9A16C28/documents/uploads"
    assert paths[-1].endswith("/complete")
    assert store["recorded"][-1] == {"document_id": "068T100000cVgi7IAC",
                                     "status": "uploaded"}


def init_fields(request_body: bytes) -> dict:
    """
    The init call's form fields.

    It is a fields-only request, so httpx encodes it as urlencoded (spaces become
    "+"), not multipart — parsing it is the only way to compare values.
    """
    return dict(httpx.QueryParams(request_body.decode()))


@pytest.mark.anyio
async def test_the_transcript_is_filed_as_an_academic_transcript(crm_on, client, store, pdf):
    """The org's vocabulary, not ours — `transcript` is not a value it accepts."""
    sent, state = client
    state["responses"] = scripted(ok_listing(), init_ok(), chunk_ok(), complete_ok())

    await upload(path=pdf, doc_type="transcript")

    fields = init_fields(sent[1]["body"])
    assert fields["document_type"] == "Academic Transcript"
    assert fields["source"] == "Internal Upload"


