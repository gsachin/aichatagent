def _clamp(n: int, cores: int) -> int:
    return max(1, min(n, cores)) if cores else max(1, n)


def _threads(spec: str, cores: int) -> int:
    """Thread specs: 'n' → min(n, cores); 'cores-2' → max(2, cores-2)."""
    if spec == "cores-2":
        return _clamp(max(2, cores - 2), cores)
    return _clamp(int(spec), cores)


