"""
Machine Profile — hardware detection, config sizing, .env management
=====================================================================
Pre-deployment machine-adaptive configuration. Detects the machine
(RAM, VRAM, CPU cores, GPU, cloud vs local), picks a sizing tier, and
merges machine-derived values into a clearly-marked block in .env.
Never touches secrets or manual overrides outside the block.

Stdlib-only by design: scripts/predeploy.py runs before the venv
exists, and app/platform.py's detect_compute_device() raises without
torch — so this module uses subprocess probes (nvidia-smi, sysctl)
and os.sysconf instead. psutil is used opportunistically when present.

Usage:
    from app.hardware_profile import detect_hardware, select_tier, apply_profile

    hw = detect_hardware()          # machine facts
    tier = select_tier(hw)          # sizing recommendation
    result = apply_profile(".env", tier)   # merge block into .env
    drift = check_drift()           # startup self-check
"""

