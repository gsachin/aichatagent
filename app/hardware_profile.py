def select_tier(hw: dict) -> dict:
    """
    Pick the sizing tier for the detected hardware. First TIERS entry whose
    platform matches and whose memory field falls in [min_mem, max_mem).

    Returns {tier_id, label, warn, values} with values covering every
    MANAGED_KEY; thread/worker counts clamped to the core count.
    """
    cores = hw.get("cpu_cores") or 1
    for t in TIERS:
        if hw.get("platform") not in t["platforms"]:
            continue
        mem = hw.get(t["mem_field"])
        if mem is None:
            continue  # unknown memory — keep scanning, fall back at the end
        if t["min_mem"] <= mem < t["max_mem"]:
            values = dict(t["values"])
            values["WHISPER_NUM_THREADS"] = str(_threads(values["WHISPER_NUM_THREADS"], cores))
            values["FASTAPI_WORKERS"] = str(_clamp(int(values["FASTAPI_WORKERS"]), cores))
            return {
                "tier_id": t["tier_id"],
                "label": t["label"],
                "warn": t.get("warn"),
                "values": values,
            }

    values = dict(FALLBACK_TIER["values"])
    values["WHISPER_NUM_THREADS"] = str(_threads(values["WHISPER_NUM_THREADS"], cores))
    values["FASTAPI_WORKERS"] = str(_clamp(int(values["FASTAPI_WORKERS"]), cores))
    return dict(tier_id=FALLBACK_TIER["tier_id"], label=FALLBACK_TIER["label"],
                warn=FALLBACK_TIER["warn"], values=values)


# ── .env block merge ──────────────────────────────────────────────────

def _read_env_text(env_path: Path) -> str:
    return env_path.read_text(encoding="utf-8", errors="replace")


def _newline_style(text: str) -> str:
    return "\r\n" if "\r\n" in text else "\n"


def _find_block(lines: list[str]) -> tuple[int, int] | None:
    """(start, end) line indices of the managed block, inclusive; None if absent."""
    start = end = None
    for i, line in enumerate(lines):
        if line.strip() == PROFILE_MARKER_OPEN:
            start = i
        elif line.strip() == PROFILE_MARKER_CLOSE and start is not None:
            end = i
            break
    if start is not None and end is not None:
        return start, end
    return None


def _key_value(line: str) -> tuple[str, str] | None:
    """Parse 'KEY=value' (leading whitespace tolerated). Returns None otherwise."""
    s = line.lstrip()
    if s.startswith("#") or "=" not in s:
        return None
    key, _, value = s.partition("=")
    return key.strip(), value.strip()


def _env_map(lines: list[str]) -> dict[str, str]:
    """First definition of each key wins (matches .env convention of one definition)."""
    out: dict[str, str] = {}
    for line in lines:
        kv = _key_value(line)
        if kv and kv[0] not in out:
            out[kv[0]] = kv[1]
    return out


def build_block(values: dict[str, str]) -> list[str]:
    """Marker-wrapped block lines for the given managed values."""
    lines = [PROFILE_MARKER_OPEN]
    lines += [f"{key}={values[key]}" for key in MANAGED_KEYS if key in values]
    lines.append(PROFILE_MARKER_CLOSE)
    return lines


def apply_profile(env_path, tier: dict, *, dry_run: bool = False, snapshot: dict | None = None) -> dict:
    """
    Merge the tier's values into .env, inside the managed block.

    Rules:
      - Lines outside the block are never modified except on first adoption.
      - First adoption (no snapshot yet): managed keys found outside the block
        are MOVED into it (action 'adopted'); a template-copied .env has no
        manual-override intent yet.
      - With a snapshot: managed keys outside the block are manual overrides
        → left untouched and omitted from the block ('manual-skip'); any stale
        copy inside the block is removed.
      - LLM_PROVIDER=auto is preserved verbatim on adoption (keeps portable
        provider auto-detection instead of pinning).
      - Idempotent: writes nothing when the result matches the file.

    Returns {changed, actions (per managed key), removed_from_block, new_content}.
    """
    path = Path(env_path)
    text = _read_env_text(path)
    nl = _newline_style(text)
    lines = text.splitlines()

    span = _find_block(lines)
    if span:
        start, end = span
        outside = lines[:start] + lines[end + 1:]
        block_lines = lines[start:end + 1]
    else:
        outside = lines[:]
        block_lines = []

    outside_map = _env_map(outside)
    block_map = _env_map(block_lines)

    actions: dict[str, str] = {}
    adopted_lines: list[str] = []   # full line texts moved from outside into the block
    new_block_values: dict[str, str] = {}
    removed_from_block: list[str] = []

    for key in MANAGED_KEYS:
        tier_value = str(tier["values"][key])
        outside_value = outside_map.get(key)

        if key in outside_map:
            if snapshot is None:
                # First adoption: the outside definition is a template leftover,
                # not a deliberate override — move it into the block.
                value = tier_value
                if key == "LLM_PROVIDER" and outside_value.lower() == "auto":
                    value = outside_value  # preserve portable auto-detection
                adopted_lines.append(key)
                actions[key] = "adopted"
            else:
                # Deliberate manual override — wins; drop any stale block copy.
                actions[key] = "manual-skip"
                if key in block_map:
                    removed_from_block.append(key)
                continue
        else:
            value = tier_value

        new_block_values[key] = value
        if key not in actions:
            # Only label when adoption didn't already do so.
            if key in block_map:
                actions[key] = "unchanged" if block_map[key] == value else "update"
            else:
                actions[key] = "insert"

    # Rebuild the file: outside (minus adopted key lines) + new block.
    kept_outside = [
        line for line in outside
        if not (_key_value(line) and _key_value(line)[0] in adopted_lines)
    ]
    block = build_block(new_block_values)

    new_lines = kept_outside
    # Normalize trailing blank lines before appending the block.
    while new_lines and new_lines[-1].strip() == "":
        new_lines.pop()
    new_lines += [""] + block
    new_text = nl.join(new_lines) + nl

    changed = new_text != text
    if not dry_run and changed:
        # Atomic write: temp file in the same directory + os.replace.
        tmp = path.with_name(path.name + ".tmp")
        tmp.write_text(new_text, encoding="utf-8")
        os.replace(tmp, path)

    return {
        "changed": changed,
        "actions": actions,
        "applied": new_block_values,  # actual values written into the block
        "removed_from_block": removed_from_block,
        "new_content": new_text if changed else None,
    }


# ── Snapshot sidecar ──────────────────────────────────────────────────

def get_snapshot_path(env_path=None) -> Path:
    """Snapshot lives next to .env (default: <repo_root>/.machine_profile.json)."""
    if env_path:
        return Path(env_path).resolve().parent / SNAPSHOT_FILENAME
    return Path(__file__).resolve().parent.parent / SNAPSHOT_FILENAME


def load_snapshot(env_path=None) -> dict | None:
    try:
        data = json.loads(get_snapshot_path(env_path).read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else None
    except (OSError, ValueError):
        return None


def _profile_id(values: dict[str, str]) -> str:
    payload = json.dumps({k: values[k] for k in sorted(values)}, sort_keys=True)
    return hashlib.sha256(payload.encode()).hexdigest()[:12]


def write_snapshot(env_path, tier: dict, hw: dict, actions: dict, removed_from_block: list[str]) -> dict:
    """
    Persist .machine_profile.json next to .env. Returns the snapshot dict.
    """
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    applied = {k: str(v) for k, v in tier["values"].items()}
    snapshot = {
        "profile_id": _profile_id(applied),
        "created_at": now,
        "updated_at": now,
        "hostname": hw.get("hostname", ""),
        "detected": {
            "os": hw.get("os"), "arch": hw.get("arch"),
            "cpu_cores": hw.get("cpu_cores"), "ram_gb": hw.get("ram_gb"),
            "device": hw.get("device"), "platform": hw.get("platform"),
            "gpu_name": hw.get("gpu_name"), "vram_gb": hw.get("vram_gb"),
            "chip_tier": hw.get("chip_tier"), "is_container": hw.get("is_container"),
        },
        "tier_id": tier.get("tier_id"),
        "tier_label": tier.get("label"),
        "applied": applied,
        "manual_overrides": [k for k, a in actions.items() if a == "manual-skip"],
        "removed_from_block": list(removed_from_block),
    }
    prev = load_snapshot(env_path)
    if prev:
        snapshot["created_at"] = prev.get("created_at", now)
    get_snapshot_path(env_path).write_text(
        json.dumps(snapshot, indent=2) + "\n", encoding="utf-8",
    )
    return snapshot


# ── Drift self-check (startup) ────────────────────────────────────────

DRIFT_TOLERANCES = {
    # (field, tolerance): numeric comparisons use these bands to absorb
    # rounding and thermal noise; strings compare exactly.
    "ram_gb": 2.0,
    "vram_gb": 1.0,
    "cpu_cores": 2,
}


def check_drift(env_path=None) -> dict:
    """
    Compare the live machine against the profile snapshot .env was sized for.

    Returns {state, diffs, tier_id, hint} where state is one of:
      ok, drifted, no_profile, skipped_container, disabled.
    """
    if os.environ.get("MACHINE_PROFILE_CHECK") == "0":
        return {"state": "disabled", "diffs": [], "tier_id": None,
                "hint": "MACHINE_PROFILE_CHECK=0"}

    snapshot = load_snapshot(env_path)
    if snapshot is None:
        return {"state": "no_profile", "diffs": [], "tier_id": None,
                "hint": "Run: python scripts/predeploy.py"}

    hw = detect_hardware()
    if hw.get("is_container"):
        return {"state": "skipped_container", "diffs": [], "tier_id": snapshot.get("tier_id"),
                "hint": "Container — host snapshot not applicable"}

    s = snapshot.get("detected", {})
    diffs = []

    for field in ("platform", "device", "gpu_name"):
        if s.get(field) is not None and hw.get(field) != s.get(field):
            diffs.append({"key": field, "snapshot": s.get(field), "live": hw.get(field)})

    for field, tol in DRIFT_TOLERANCES.items():
        sv, lv = s.get(field), hw.get(field)
        if sv is not None and lv is not None and abs(float(lv) - float(sv)) > tol:
            diffs.append({"key": field, "snapshot": sv, "live": lv})

    if diffs:
        return {"state": "drifted", "diffs": diffs, "tier_id": snapshot.get("tier_id"),
                "hint": "Machine changed since config was sized — re-run: python scripts/predeploy.py"}

    return {"state": "ok", "diffs": [], "tier_id": snapshot.get("tier_id"), "hint": ""}
