# ── Hardware detection (stdlib-only) ──────────────────────────────────

def _run(cmd: list[str]) -> str:
    """Run a command, return stripped stdout, or "" on any failure."""
    try:
        out = subprocess.run(
            cmd, capture_output=True, text=True, timeout=10,
        )
        return out.stdout.strip()
    except Exception:
        return ""


def _total_ram_gb() -> float | None:
    """System RAM in GB. psutil → POSIX sysconf → macOS sysctl → Windows ctypes."""
    try:
        import psutil
        return round(psutil.virtual_memory().total / (1024**3), 1)
    except Exception:
        pass
    if sys.platform == "darwin":
        raw = _run(["sysctl", "-n", "hw.memsize"])
        try:
            return round(int(raw) / (1024**3), 1)
        except ValueError:
            pass
    if hasattr(os, "sysconf"):
        try:
            pages, page_size = os.sysconf("SC_PHYS_PAGES"), os.sysconf("SC_PAGE_SIZE")
            if pages > 0 and page_size > 0:
                return round(pages * page_size / (1024**3), 1)
        except (ValueError, OSError):
            pass
    if sys.platform == "win32":
        try:
            import ctypes

            class _MEMORYSTATUSEX(ctypes.Structure):
                _fields_ = [
                    ("dwLength", ctypes.c_ulong), ("dwMemoryLoad", ctypes.c_ulong),
                    ("ullTotalPhys", ctypes.c_ulonglong), ("ullAvailPhys", ctypes.c_ulonglong),
                    ("ullTotalPageFile", ctypes.c_ulonglong), ("ullAvailPageFile", ctypes.c_ulonglong),
                    ("ullTotalVirtual", ctypes.c_ulonglong), ("ullAvailVirtual", ctypes.c_ulonglong),
                    ("ullAvailExtendedVirtual", ctypes.c_ulonglong),
                ]

            stat = _MEMORYSTATUSEX()
            stat.dwLength = ctypes.sizeof(_MEMORYSTATUSEX)
            if ctypes.windll.kernel32.GlobalMemoryStatusEx(ctypes.byref(stat)):
                return round(stat.ullTotalPhys / (1024**3), 1)
        except Exception:
            pass
    return None


def _nvidia_gpu() -> tuple[str, float] | None:
    """(gpu_name, vram_gb) from nvidia-smi, or None."""
    out = _run(["nvidia-smi", "--query-gpu=name,memory.total", "--format=csv,noheader"])
    if not out:
        return None
    line = out.splitlines()[0]
    parts = [p.strip() for p in line.split(",")]
    if len(parts) < 2:
        return None
    m = re.search(r"(\d+(?:\.\d+)?)\s*MiB", parts[1])
    if not m:
        return None
    return parts[0], round(int(m.group(1)) / 1024, 1)


def _mac_chip() -> str:
    """Chip name on Apple Silicon (e.g. 'Apple M3 Max'), else ''."""
    return (
        _run(["sysctl", "-n", "machdep.cpu.brand_string"])
        or _run(["sysctl", "-n", "hw.model"])
    )


def _is_container() -> bool:
    if os.environ.get("MACHINE_IN_CONTAINER") == "1":
        return True
    if sys.platform == "linux":
        try:
            cgroup = Path("/proc/1/cgroup").read_text()
            if any(t in cgroup for t in ("docker", "kubepods", "containerd")):
                return True
        except OSError:
            pass
        if Path("/run/.containerenv").exists():
            return True
    return False


def detect_hardware() -> dict:
    """
    Machine facts, stdlib-only. Never raises.

    Returns keys: os, arch, hostname, cpu_cores, ram_gb, device, platform,
    gpu_name, vram_gb, chip_tier, is_container, cloud.
    """
    system = _platform.system().lower()  # darwin / windows / linux
    arch = _platform.machine()
    cpu_cores = os.cpu_count() or 1
    ram_gb = _total_ram_gb()

    nv = _nvidia_gpu()
    chip = _mac_chip() if system == "darwin" else ""
    container = _is_container()

    if nv:
        device, platform, gpu_name, vram_gb = "cuda", "nvidia", nv[0], nv[1]
        chip_tier = nv[0]
    elif system == "darwin" and arch in ("arm64", "aarch64"):
        device, platform, gpu_name, vram_gb = "mps", "apple_silicon", chip, ram_gb
        chip_tier = chip
    elif system == "darwin":
        device, platform, gpu_name, vram_gb = "cpu", "intel_mac", chip, None
        chip_tier = chip
    else:
        device, platform, gpu_name, vram_gb = "cpu", "cpu", "", None
        chip_tier = ""

    cloud = (
        platform == "cpu"
        and system == "linux"
        and (container or os.environ.get("MACHINE_CLOUD") == "1" or Path("/etc/cloud").exists())
    )
    if cloud:
        platform = "cloud_linux"

    return {
        "os": system,
        "arch": arch,
        "hostname": socket.gethostname(),
        "cpu_cores": cpu_cores,
        "ram_gb": ram_gb,
        "device": device,
        "platform": platform,
        "gpu_name": gpu_name,
        "vram_gb": vram_gb,
        "chip_tier": chip_tier,
        "is_container": container,
        "cloud": cloud,
    }


